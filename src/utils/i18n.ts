/**
 * Universal text translator helper
 */
export function t(key: string, currentLang: SupportedLanguage, fallback?: string): string {
  const resolvedKey = KEY_ALIASES[key] || key;
  const langDict = TRANSLATIONS[currentLang];
  if (langDict) {
    if (langDict[key]) return langDict[key];
    if (langDict[resolvedKey]) return langDict[resolvedKey];
  }
  // Fallback to explicit fallback or English dictionary
  if (fallback && currentLang === 'en') {
    return fallback;
  }
  if (TRANSLATIONS.en[key]) {
    return TRANSLATIONS.en[key];
  }
  if (TRANSLATIONS.en[resolvedKey]) {
    return TRANSLATIONS.en[resolvedKey];
  }
  return fallback || key;
}
