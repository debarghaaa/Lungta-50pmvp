// Storage Key
const LANGUAGE_STORAGE_KEY = 'lungta_selected_language_v1';

export function getStoredLanguage(): SupportedLanguage {
  if (typeof window === 'undefined') return 'en';
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (stored && SUPPORTED_LANGUAGES.some((l) => l.code === stored)) {
      return stored as SupportedLanguage;
    }
  } catch {
    // fallback
  }
  return 'en';
}

export function setStoredLanguage(lang: SupportedLanguage) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    window.dispatchEvent(
      new CustomEvent('lungta_language_changed', { detail: { language: lang } })
    );
  } catch {
    // ignore
  }
}

export function getLanguageMeta(code: SupportedLanguage): LanguageMeta {
  return (
    SUPPORTED_LANGUAGES.find((l) => l.code === code) || SUPPORTED_LANGUAGES[0]
  );
}

